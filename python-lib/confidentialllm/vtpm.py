"""GCE Confidential VM attestation through the Google-managed vTPM (used for AMD SEV VMs such as G4).

Plain AMD SEV has no hardware attestation report, so the evidence is a TPM2 quote signed by the VM's
attestation key (AK). What this proves, in order:

1. The AK certificate chains to Google's EK/AK CA (bundled in ``gce_ca``): the key belongs to a GCE vTPM.
2. The quote is signed by that AK and its ``extraData`` is this request's digest (nonce + gateway HPKE key).
3. The quoted SHA-256 PCR values hash to the quote's ``pcrDigest``.
4. The TCG event log replays to the quoted PCR0 and PCR7, so its PCR0 "GCE NonHostInfo" event (the
   Confidential VM technology) and PCR7 SecureBoot variable can be trusted.

The root of trust is Google's hypervisor and vTPM, not the CPU vendor. The formats follow the TPM 2.0
spec (part 2), the TCG PC Client Platform Firmware Profile, and go-tpm-tools / go-eventlog.
"""

import hashlib
import hmac
import struct
import warnings
from dataclasses import dataclass
from datetime import datetime, timezone

from .errors import AttestationError

# --- TPM constants (TPM 2.0 part 2) ---------------------------------------------------------------
TPM_GENERATED_VALUE = 0xFF544347
TPM_ST_ATTEST_QUOTE = 0x8018
TPM_ALG_RSASSA = 0x0014
TPM_ALG_RSAPSS = 0x0016
TPM_ALG_ECDSA = 0x0018
TPM_ALG_SHA1 = 0x0004
TPM_ALG_SHA256 = 0x000B
TPM_ALG_SHA384 = 0x000C
TPM_ALG_SHA512 = 0x000D

# --- TCG event log constants ---------------------------------------------------------------------
EV_NO_ACTION = 0x00000003
EV_SEPARATOR = 0x00000004
EV_NONHOST_INFO = 0x00000011
EV_EFI_VARIABLE_DRIVER_CONFIG = 0x80000001
SPEC_ID_SIGNATURE = b"Spec ID Event03\x00"
STARTUP_LOCALITY_SIGNATURE = b"StartupLocality\x00"
GCE_NONHOST_SIGNATURE = b"GCE NonHostInfo\x00"
EFI_GLOBAL_VARIABLE_GUID = bytes.fromhex("61dfe48bca93d211aa0d00e098032b8c")  # 8BE4DF61-93CA-11D2-AA0D-00E098032B8C, mixed-endian

# GCEConfidentialTechnology (go-eventlog proto/state): the byte after the NonHostInfo signature.
TECHNOLOGIES = {0: "NONE", 1: "AMD_SEV", 2: "AMD_SEV_ES", 3: "INTEL_TDX", 4: "AMD_SEV_SNP"}

# AK certificate extension with the GCE instance identity (go-tpm-tools server/verify.go).
GCE_INSTANCE_INFO_OID = "1.3.6.1.4.1.11129.2.1.21"

PCR_KEYS = ("pcr0", "pcr4", "pcr7", "pcr8", "pcr9")
REQUIRED_PCRS = (0, 7)  # parsed from the event log; pinned PCRs are added at verification time
MAX_CHAIN_LENGTH = 5


# --- small binary readers ------------------------------------------------------------------------
class _Reader:
    def __init__(self, data, endian):
        self.data, self.pos, self.endian = bytes(data), 0, endian

    def take(self, n):
        if n < 0 or self.pos + n > len(self.data):
            raise AttestationError("Truncated vTPM structure.")
        out = self.data[self.pos:self.pos + n]
        self.pos += n
        return out

    def uint(self, size):
        fmt = {1: "B", 2: "H", 4: "I", 8: "Q"}[size]
        return struct.unpack(self.endian + fmt, self.take(size))[0]

    def tpm2b(self):
        return self.take(self.uint(2))

    @property
    def remaining(self):
        return len(self.data) - self.pos


# --- quote ---------------------------------------------------------------------------------------
@dataclass(frozen=True)
class Quote:
    extra_data: bytes
    selection: tuple  # ((hash_alg, (pcr indices...)), ...)
    pcr_digest: bytes


def parse_quote(raw):
    """Parse a TPMS_ATTEST of type TPM_ST_ATTEST_QUOTE."""
    r = _Reader(raw, ">")
    if r.uint(4) != TPM_GENERATED_VALUE:
        raise AttestationError("The vTPM quote was not generated by a TPM (bad magic).")
    if r.uint(2) != TPM_ST_ATTEST_QUOTE:
        raise AttestationError("The vTPM evidence is not a quote.")
    r.tpm2b()  # qualifiedSigner (AK name); the AK is identified by its certificate instead
    extra_data = r.tpm2b()
    r.take(8 + 4 + 4 + 1)  # clockInfo
    r.take(8)  # firmwareVersion
    selection = []
    for _ in range(r.uint(4)):
        alg = r.uint(2)
        bitmap = r.take(r.uint(1))
        selection.append((alg, tuple(8 * i + bit for i, byte in enumerate(bitmap) for bit in range(8) if byte >> bit & 1)))
    pcr_digest = r.tpm2b()
    if r.remaining:
        raise AttestationError("Unexpected trailing bytes in the vTPM quote.")
    return Quote(extra_data=extra_data, selection=tuple(selection), pcr_digest=pcr_digest)


def _hash_for(alg):
    from cryptography.hazmat.primitives import hashes

    try:
        return {TPM_ALG_SHA256: hashes.SHA256(), TPM_ALG_SHA384: hashes.SHA384(), TPM_ALG_SHA512: hashes.SHA512()}[alg]
    except KeyError:
        raise AttestationError("Unsupported vTPM signature hash algorithm 0x{:04x}.".format(alg)) from None


def verify_quote_signature(public_key, quote_raw, signature_raw):
    """Verify a TPMT_SIGNATURE over the quote with the AK public key."""
    from cryptography.exceptions import InvalidSignature
    from cryptography.hazmat.primitives.asymmetric import ec, padding, rsa
    from cryptography.hazmat.primitives.asymmetric.utils import encode_dss_signature

    r = _Reader(signature_raw, ">")
    sig_alg = r.uint(2)
    hash_alg = _hash_for(r.uint(2))
    try:
        if sig_alg == TPM_ALG_ECDSA and isinstance(public_key, ec.EllipticCurvePublicKey):
            sig_r, sig_s = int.from_bytes(r.tpm2b(), "big"), int.from_bytes(r.tpm2b(), "big")
            signature = encode_dss_signature(sig_r, sig_s)
            if r.remaining:
                raise AttestationError("Unexpected trailing bytes in the vTPM signature.")
            public_key.verify(signature, quote_raw, ec.ECDSA(hash_alg))
        elif sig_alg in (TPM_ALG_RSASSA, TPM_ALG_RSAPSS) and isinstance(public_key, rsa.RSAPublicKey):
            signature = r.tpm2b()
            if r.remaining:
                raise AttestationError("Unexpected trailing bytes in the vTPM signature.")
            pad = padding.PKCS1v15() if sig_alg == TPM_ALG_RSASSA else padding.PSS(
                mgf=padding.MGF1(hash_alg), salt_length=padding.PSS.AUTO)
            public_key.verify(signature, quote_raw, pad, hash_alg)
        else:
            raise AttestationError("The vTPM signature algorithm does not match the attestation key.")
    except InvalidSignature:
        raise AttestationError("The vTPM quote signature does not verify with the attestation key.") from None


def check_pcr_digest(quote, pcrs, required):
    """The quoted PCR selection must be SHA-256, cover ``required``, and hash to the quote's pcrDigest."""
    if len(quote.selection) != 1 or quote.selection[0][0] != TPM_ALG_SHA256:
        raise AttestationError("The vTPM quote must cover exactly one PCR bank, SHA-256.")
    indices = quote.selection[0][1]
    missing = sorted(set(required) - set(indices))
    if missing:
        raise AttestationError("The vTPM quote does not cover PCR {}.".format(", ".join(map(str, missing))))
    try:
        concatenated = b"".join(pcrs[i] for i in indices)
    except KeyError as exc:
        raise AttestationError("The gateway did not send the value of quoted PCR {}.".format(exc.args[0])) from None
    if any(len(pcrs[i]) != 32 for i in indices):
        raise AttestationError("A SHA-256 PCR value is not 32 bytes.")
    if not hmac.compare_digest(hashlib.sha256(concatenated).digest(), quote.pcr_digest):
        raise AttestationError("The PCR values do not match the quote's PCR digest.")


# --- AK certificate chain ------------------------------------------------------------------------
def _load_der(der):
    from cryptography import x509

    with warnings.catch_warnings():  # Google's legacy CA names exceed the 64-character X.520 CN limit
        warnings.simplefilter("ignore", UserWarning)
        return x509.load_der_x509_certificate(der)


def _load_pem(pem):
    from cryptography import x509

    with warnings.catch_warnings():
        warnings.simplefilter("ignore", UserWarning)
        return x509.load_pem_x509_certificate(pem.encode() if isinstance(pem, str) else pem)


def _is_ca(cert):
    from cryptography import x509

    try:
        return cert.extensions.get_extension_for_class(x509.BasicConstraints).value.ca
    except x509.ExtensionNotFound:
        return False


def _check_validity(cert, now):
    if not cert.not_valid_before_utc <= now <= cert.not_valid_after_utc:
        raise AttestationError("Certificate {} is outside its validity period.".format(cert.subject.rfc4514_string()[:80]))


def _issued_by(cert, issuer):
    try:
        cert.verify_directly_issued_by(issuer)
        return True
    except Exception:  # ValueError (name mismatch), InvalidSignature, TypeError (unsupported key)
        return False


def verify_ak_chain(ak_cert, intermediates, roots, now=None):
    """Return the chain [ak, ..., root] if ``ak_cert`` chains to one of ``roots``; raise otherwise."""
    with warnings.catch_warnings():  # names are parsed lazily; Google's legacy CNs exceed 64 characters
        warnings.simplefilter("ignore", UserWarning)
        return _build_chain(ak_cert, intermediates, roots, now or datetime.now(timezone.utc))


def _build_chain(ak_cert, intermediates, roots, now):
    chain, current = [ak_cert], ak_cert
    _check_validity(ak_cert, now)
    for _ in range(MAX_CHAIN_LENGTH):
        for root in roots:
            if root.subject == current.issuer and _issued_by(current, root):
                _check_validity(root, now)
                return chain + [root]
        parent = next((c for c in intermediates if c.subject == current.issuer and _is_ca(c) and _issued_by(current, c)), None)
        if parent is None or parent in chain:
            break
        _check_validity(parent, now)
        chain.append(parent)
        current = parent
    raise AttestationError("The vTPM attestation key certificate does not chain to Google's EK/AK CA.")


def default_roots():
    from . import gce_ca

    return [_load_pem(p) for p in gce_ca.ROOTS], [_load_pem(p) for p in gce_ca.INTERMEDIATES]


# --- GCE instance identity (AK certificate extension) --------------------------------------------
def _der_items(data):
    """Split concatenated DER TLVs into [(tag, value)]. Only definite lengths (DER)."""
    items, pos = [], 0
    while pos < len(data):
        if pos + 2 > len(data):
            raise ValueError("truncated")
        tag, length = data[pos], data[pos + 1]
        pos += 2
        if length & 0x80:
            n = length & 0x7F
            if n == 0 or n > 4 or pos + n > len(data):
                raise ValueError("bad length")
            length = int.from_bytes(data[pos:pos + n], "big")
            pos += n
        if pos + length > len(data):
            raise ValueError("truncated")
        items.append((tag, data[pos:pos + length]))
        pos += length
    return items


def parse_instance_info(ak_cert):
    """Return the GCE instance identity from the AK certificate, or None (absent, or not a production VM).

    Mirrors go-tpm-tools ``GetGCEInstanceInfo``: SEQUENCE { zone UTF8String, project_number INTEGER,
    project_id UTF8String, instance_id INTEGER, instance_name UTF8String, security_properties SEQUENCE {
    [0] security_version INTEGER, [1] is_production BOOLEAN } }. Only trust this after verify_ak_chain.
    """
    from cryptography import x509

    try:
        raw = ak_cert.extensions.get_extension_for_oid(x509.ObjectIdentifier(GCE_INSTANCE_INFO_OID)).value.value
    except x509.ExtensionNotFound:
        return None
    try:
        (tag, body), = _der_items(raw)
        fields = _der_items(body)
        if tag != 0x30 or [t for t, _ in fields[:5]] != [0x0C, 0x02, 0x0C, 0x02, 0x0C]:
            raise ValueError("unexpected layout")
        is_production = False
        for t, v in fields[5:6]:
            if t == 0xA0:  # tolerate an explicit [0] wrapper around the SEQUENCE
                (t, v), = _der_items(v)
            props = _der_items(v) if t == 0x30 else []
            for ptag, pval in props:
                if ptag == 0xA1:
                    (btag, bval), = _der_items(pval)
                    is_production = btag == 0x01 and bval not in (b"", b"\x00")
        if not is_production:
            return None
        return {
            "zone": fields[0][1].decode("utf-8"),
            "project_number": int.from_bytes(fields[1][1], "big", signed=True),
            "project_id": fields[2][1].decode("utf-8"),
            "instance_id": str(int.from_bytes(fields[3][1], "big", signed=True)),
            "instance_name": fields[4][1].decode("utf-8"),
        }
    except (ValueError, UnicodeDecodeError) as exc:
        raise AttestationError("The GCE instance identity in the AK certificate is malformed: {}".format(exc)) from exc


# --- TCG event log -------------------------------------------------------------------------------
@dataclass(frozen=True)
class Event:
    pcr: int
    type: int
    digest: bytes  # the SHA-256 digest; None if the log has no SHA-256 bank entry for this event
    data: bytes


def parse_event_log(raw):
    """Parse a crypto-agile (TCG2) event log and return its events with their SHA-256 digests."""
    r = _Reader(raw, "<")
    # First event: legacy TCG_PCR_EVENT carrying the Spec ID header.
    r.uint(4)
    if r.uint(4) != EV_NO_ACTION:
        raise AttestationError("The event log does not start with a Spec ID event.")
    r.take(20)
    header = _Reader(r.take(r.uint(4)), "<")
    if header.take(16) != SPEC_ID_SIGNATURE:
        raise AttestationError("The event log is not in the crypto-agile (TCG2) format.")
    header.take(4 + 1 + 1 + 1 + 1)  # platformClass, version, errata, uintnSize
    sizes = {}
    for _ in range(header.uint(4)):
        alg = header.uint(2)
        sizes[alg] = header.uint(2)
    if TPM_ALG_SHA256 not in sizes:
        raise AttestationError("The event log has no SHA-256 bank.")

    events = []
    while r.remaining:
        if not any(r.data[r.pos:]):  # some firmware pads the log with zeros
            break
        pcr, event_type = r.uint(4), r.uint(4)
        digest = None
        for _ in range(r.uint(4)):
            alg = r.uint(2)
            if alg not in sizes:
                raise AttestationError("The event log uses an undeclared hash algorithm 0x{:04x}.".format(alg))
            value = r.take(sizes[alg])
            if alg == TPM_ALG_SHA256:
                digest = value
        events.append(Event(pcr=pcr, type=event_type, digest=digest, data=r.take(r.uint(4))))
    return events


def replay(events, indices):
    """Recompute the SHA-256 PCRs ``indices`` from the event log."""
    pcrs = {i: bytes(32) for i in indices}
    for event in events:
        if event.pcr not in pcrs:
            continue
        if event.type == EV_NO_ACTION:
            if event.pcr == 0 and event.data.startswith(STARTUP_LOCALITY_SIGNATURE) and len(event.data) >= 17:
                pcrs[0] = bytes(31) + event.data[16:17]
            continue
        if event.digest is None:
            raise AttestationError("An event for PCR {} has no SHA-256 digest.".format(event.pcr))
        pcrs[event.pcr] = hashlib.sha256(pcrs[event.pcr] + event.digest).digest()
    return pcrs


def _digest_matches(event):
    return event.digest is not None and hmac.compare_digest(hashlib.sha256(event.data).digest(), event.digest)


def _events_before_separator(events, pcr):
    """Events of ``pcr`` up to its first separator. Later events are not trusted (they come after the firmware)."""
    for event in events:
        if event.pcr != pcr:
            continue
        if event.type == EV_SEPARATOR:
            if event.data not in (b"\x00\x00\x00\x00", b"\xff\xff\xff\xff") or not _digest_matches(event):
                raise AttestationError("Invalid separator event for PCR {}.".format(pcr))
            return
        yield event


def confidential_technology(events):
    """Read the GCE Confidential VM technology from the PCR0 NonHostInfo event (go-eventlog ParseGCENonHostInfo)."""
    found = None
    for event in _events_before_separator(events, 0):
        if event.type == EV_NONHOST_INFO:
            if not _digest_matches(event):
                raise AttestationError("The GCE NonHostInfo event does not match its digest.")
            found = event.data
    if found is None or len(found) < 17 or not found.startswith(GCE_NONHOST_SIGNATURE):
        raise AttestationError("The event log has no GCE NonHostInfo event: this is not a GCE Confidential VM.")
    try:
        return TECHNOLOGIES[found[16]]
    except KeyError:
        raise AttestationError("Unknown GCE Confidential VM technology {}.".format(found[16])) from None


def secure_boot_enabled(events):
    """Read the SecureBoot UEFI variable measured into PCR7 (UEFI_VARIABLE_DATA)."""
    for event in _events_before_separator(events, 7):
        if event.type != EV_EFI_VARIABLE_DRIVER_CONFIG:
            continue
        r = _Reader(event.data, "<")
        guid = r.take(16)
        name_len, data_len = r.uint(8), r.uint(8)
        name = r.take(2 * name_len).decode("utf-16-le", errors="replace")
        value = r.take(data_len)
        if guid == EFI_GLOBAL_VARIABLE_GUID and name == "SecureBoot":
            if not _digest_matches(event):
                raise AttestationError("The SecureBoot event does not match its digest.")
            return value == b"\x01"
    return False


# --- entry point ---------------------------------------------------------------------------------
def _b64(evidence, key):
    import base64

    try:
        return base64.b64decode(evidence[key], validate=True)
    except (KeyError, ValueError, TypeError) as exc:
        raise AttestationError("The vTPM evidence has no valid '{}'.".format(key)) from exc


def verify_evidence(evidence, digest, pinned_pcrs=(), roots=None, intermediates=None, now=None):
    """Verify the vTPM evidence and return (measurements, platform).

    ``measurements`` holds pcr0/4/7/8/9 (hex) and, when present, the GCE ``instance_id``; ``platform``
    holds the technology, Secure Boot state and instance identity, for display.
    """
    import base64

    if not isinstance(evidence, dict):
        raise AttestationError("The gateway returned no vTPM evidence.")
    if roots is None:
        roots, bundled = default_roots()
        intermediates = list(intermediates or []) + bundled
    try:
        ak_cert = _load_der(_b64(evidence, "ak_cert_der_b64"))
        sent = [_load_der(base64.b64decode(c, validate=True)) for c in evidence.get("intermediates_der_b64") or []]
    except AttestationError:
        raise
    except Exception as exc:
        raise AttestationError("The vTPM certificates are malformed: {}".format(exc)) from exc
    verify_ak_chain(ak_cert, sent + list(intermediates or []), roots, now)

    quote_raw = _b64(evidence, "quote_b64")
    verify_quote_signature(ak_cert.public_key(), quote_raw, _b64(evidence, "signature_b64"))
    quote = parse_quote(quote_raw)
    if not hmac.compare_digest(quote.extra_data, digest):
        raise AttestationError(
            "The vTPM quote does not commit to this request's nonce and the gateway's encryption key. "
            "It is stale, replayed, or belongs to a different key.")

    try:
        pcrs = {int(k): bytes.fromhex(v) for k, v in (evidence.get("pcrs") or {}).items()}
    except (ValueError, TypeError, AttributeError) as exc:
        raise AttestationError("The vTPM PCR values are malformed.") from exc
    required = set(REQUIRED_PCRS) | {int(k[3:]) for k in PCR_KEYS} | set(pinned_pcrs)
    check_pcr_digest(quote, pcrs, required)

    events = parse_event_log(_b64(evidence, "event_log_b64"))
    replayed = replay(events, REQUIRED_PCRS)
    for index in REQUIRED_PCRS:
        if not hmac.compare_digest(replayed[index], pcrs[index]):
            raise AttestationError("The event log does not replay to the quoted PCR {}.".format(index))
    technology = confidential_technology(events)
    if technology == "NONE":
        raise AttestationError("The VM is not a Confidential VM (GCE confidential technology: NONE).")
    secure_boot = secure_boot_enabled(events)
    if not secure_boot:
        raise AttestationError("Secure Boot is not enabled on the VM.")

    instance = parse_instance_info(ak_cert)
    measurements = {key: pcrs[int(key[3:])].hex() for key in PCR_KEYS}
    if instance:
        measurements["instance_id"] = instance["instance_id"]
    return measurements, {"technology": technology, "secure_boot": secure_boot, "instance": instance}
